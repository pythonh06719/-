-- -----------------------------------------------------------------------------
-- 1. users
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email              TEXT        NOT NULL,
  password_hash      TEXT,
  email_verified_at  TIMESTAMPTZ,
  status             TEXT        NOT NULL DEFAULT 'active' CHECK (status IN ('active','disabled')),
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_email ON users(email);

-- -----------------------------------------------------------------------------
-- 2. auth_verification_codes
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS auth_verification_codes (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email        TEXT        NOT NULL,
  code_hash    TEXT        NOT NULL,
  purpose      TEXT        NOT NULL DEFAULT 'login' CHECK (purpose IN ('login','signup','reset')),
  expires_at   TIMESTAMPTZ NOT NULL,
  consumed_at  TIMESTAMPTZ,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_avc_email_purpose ON auth_verification_codes(email, purpose, expires_at);

-- -----------------------------------------------------------------------------
-- 3. user_profiles
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS user_profiles (
  user_id                BIGINT      PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  gender                 TEXT        NOT NULL CHECK (gender IN ('male','female')),
  birth_date             DATE        NOT NULL,
  height_cm              DOUBLE PRECISION NOT NULL CHECK (height_cm > 0),
  activity_level         TEXT        NOT NULL CHECK (activity_level IN ('sedentary','light','moderate','high','athlete')),
  dietary_preference     TEXT        NOT NULL DEFAULT '[]',   -- JSON 文本（应用层 JSON.parse）
  conditions             TEXT        NOT NULL DEFAULT '[]',   -- JSON 文本；敏感字段（D3）
  disclaimer_accepted_at TIMESTAMPTZ,
  onboarding_completed_at TIMESTAMPTZ,
  created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at             TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- -----------------------------------------------------------------------------
-- 4. user_goals
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS user_goals (
  user_id          BIGINT      PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  start_weight_kg  DOUBLE PRECISION NOT NULL,
  target_weight_kg DOUBLE PRECISION NOT NULL CHECK (target_weight_kg > 0),
  target_weeks     INTEGER     NOT NULL CHECK (target_weeks > 0),
  weekly_loss_kg   DOUBLE PRECISION NOT NULL CHECK (weekly_loss_kg > 0),
  macro_ratio      TEXT        NOT NULL DEFAULT '{"protein":25,"fat":25,"carb":50}',  -- JSON 文本
  is_active        BOOLEAN     NOT NULL DEFAULT TRUE,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- -----------------------------------------------------------------------------
-- 5. weight_goal_history
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS weight_goal_history (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id          BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  start_weight_kg  DOUBLE PRECISION NOT NULL,
  target_weight_kg DOUBLE PRECISION NOT NULL,
  target_weeks     INTEGER     NOT NULL,
  weekly_loss_kg   DOUBLE PRECISION NOT NULL,
