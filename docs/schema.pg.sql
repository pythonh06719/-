-- -----------------------------------------------------------------------------
-- 21. ai_traces —— Agent 执行轨迹（可观测性：工具调用链 / 耗时 / token / 结果）
--     steps / pending_tool 为 JSON 文本（TEXT），由应用层 JSON.parse/stringify；
--     pending_tool 仅在待用户确认时非空，确认/抢占后置 NULL。
--     本表无 updated_at（追加式轨迹，不更新），故不参与下方 updated_at 触发器集合。
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ai_traces (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  question     TEXT        NOT NULL,
  status       TEXT        NOT NULL
               CHECK (status IN ('answered','need_confirm','max_steps','failed','disabled')),
  answer       TEXT,
  steps        TEXT        NOT NULL,        -- JSON 文本：AgentStep[]
  pending_tool TEXT,                        -- JSON 文本：{ name, args }；无待确认时为 NULL
  tool_calls   INTEGER     NOT NULL DEFAULT 0,
  tokens       INTEGER     NOT NULL DEFAULT 0,
  duration_ms  INTEGER     NOT NULL DEFAULT 0,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_ai_traces_user_id ON ai_traces(user_id, id);

-- =============================================================================
-- updated_at 自动维护（PG 原生支持触发器函数）
-- =============================================================================
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'users','user_profiles','user_goals','user_settings','weight_logs',
    'food_items','meal_logs','meal_combos','exercise_logs',
    'habit_definitions','fasting_settings','fasting_sessions','ai_usage'
  ] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_%s_touch ON %I;', t, t);
    EXECUTE format('CREATE TRIGGER trg_%s_touch BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION set_updated_at();', t, t);
  END LOOP;
END $$;
