/**
 * 份量模板表（「食物库扩量」T3）。
 *
 * 背景：CFCD（中国食物成分表）平台的「食部」是**可食部百分比**、**全站无份量数据**；
 * 而本项目校验要求每条 `servingUnits[].grams > 0`（fail-fast）。故按**二级分类**给一套
 * 常识份量模板。
 *
 * 放置位置选择理由：这是**种子导入专用数据**（与 CFCD 的 91 个二级分类强绑定），
 * 不是通用业务逻辑；放进 `@qsh/core` 会让通用纯函数库耦合「中国食物成分表分类体系」，
 * 故与 `import-cfcd.ts` 同置于 `infra/db/seed/` 下，就近维护、零运行时依赖。
 *
 * 取值原则：
 * - 有把握的分类给**贴近中式饮食的常识份量**（如「稻米 → 小碗 150g」「鸡蛋 → 个 50g」）；
 * - **无把握的一律兜底** `[{unit:'100克', grams:100, isDefault:true}]`——能过校验，
 *   虽语义偏弱但**不捏造**具体份量。
 *
 * 键：`一级分类名/二级分类名`（二级 id 全局唯一，但显示名有重复——如多个「其它」，
 * 故用「一级/二级」组合避免歧义）。
 */

/** 自然份量单位。 */
export interface ServingUnit {
  unit: string;
  grams: number;
  isDefault?: boolean;
  label?: string;
}

/** 兜底份量（无把握时使用）。 */
export const DEFAULT_SERVING: readonly ServingUnit[] = [{ unit: '100克', grams: 100, isDefault: true }];

/** 常用份量的简写构造器。 */
const u = (unit: string, grams: number, label?: string, isDefault = false): ServingUnit => ({
  unit,
  grams,
  ...(label ? { label } : {}),
  ...(isDefault ? { isDefault: true } : {}),
});

