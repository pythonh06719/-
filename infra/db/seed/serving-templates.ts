/**
 * 取某二级分类的份量模板（未命中返回兜底 `DEFAULT_SERVING` 的新副本）。
 *
 * @param categoryOneName 一级分类名（如「谷类及制品」）
 * @param categoryTwoName 二级分类名（如「稻米」）
 */
export function servingFor(categoryOneName: string, categoryTwoName: string): ServingUnit[] {
  const tmpl = SERVING_TEMPLATES[`${categoryOneName}/${categoryTwoName}`];
  const source = tmpl ?? DEFAULT_SERVING;
  return source.map((s) => ({ ...s }));
}
