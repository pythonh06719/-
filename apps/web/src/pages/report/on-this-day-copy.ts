/**
 * 「历史上的今天」（D-4）的用户可见文案。
 *
 * ## ⚠️ 为什么不放在 `lib/copy.ts`（与项目惯例的偏离，**有意为之**）
 *
 * `lib/copy.ts` 是多人高频共改的中央文案表，本任务执行期间**另一个工程师正在同一个
 * 文件里做 D-5**。而 `git commit -- <path>` 会连带提交该路径工作树的**全部**内容 ——
 * 提交我的功能就等于把别人的在制品一起提交走 theirs。
 *
 * 故 D-4 的文案收敛到本文件（**功能内聚、零冲突**），待 D-5 落库后
 * 可在一次纯文案提交里并回 `copy.ts`（届时只需改import，逻辑不动）。
 *
 * ## 语气红线（本功能**最容易踩错**的地方）
 *
 * 这个功能的全部价值在于「唤起美好的记忆」，而它最容易被做成「缺席指控」。
 * 因此下面这些键是**刻意不存在**的，不是漏写：
 *
 * - ⛔ 没有 `onThisDayEmpty` / `onThisDayNoRecord` —— 红线要求**无历史时整块隐藏**，
 *   不留空卡、不给「暂无历史」引导语。一旦存在这种文案，功能即变成缺席指控；
 * - ⛔ 没有「共 N 餐」「连续 N 天」「N 天没记」这类带分母 / 缺席语义的句子；
 * - ⛔ 没有催促 / 持恒类表述（「别荒废」「要坚持」）。
 *
 * 措辞一律「**只陈述那一天吃了什么**」，不比较、不评价、不建议、不提醒。
 */

/** 回望卡标题。 */
export const ON_THIS_DAY_TITLE = '历史上的今天';

/** 时间尺度标签：**一次只呈现一个**，故这里是两个互斥的备选而非一个「可切换项」。 */
export const ON_THIS_DAY_SCALE_LABEL = {
  /** 一年前 */
  year: '一年前的今天',
  /** 一个月前（一年前那天没有记录时**顺延**到这里，用户看不到任何「缺失」痕迹） */
  month: '一个月前的今天',
} as const;

/**
 * 回望正文引导语。
 *
 * 只说「吃了什么」，**不说记了几餐 / 记了多少天** —— 一旦出现计数，
 * 就等于给这段记忆塞了一个分母，记忆立刻变成考核。
 */
export const ON_THIS_DAY_LEAD = '那天你吃了这些';

/**
 * 尾注 —— 把「这只是回看，不是任务」讲清楚。
 *
 * ⚠️ 反缺席指控的关键句：明确「翻出来一次」是自愿的、随时可停，
 * 不给「要保持」「别断」这类压力。
 */
export const ON_THIS_DAY_FOOTNOTE = '看到这些，就当那天又翻出来一次';

/** 点进那一天完整档案的按钮文案。 */
export const ON_THIS_DAY_OPEN_FULL = '看看那天';

/**
 * 该日期行的读屏标签：带完整日期，不含评判词。
 *
 * @param dateLabel 形如「2025年9月30日 · 周二」
 */
export function onThisDayOpenFullAria(dateLabel: string): string {
  return `看看 ${dateLabel} 的完整记录`;
}