/**
 * 体重批量导入的**分批常量**（单独成文件，方便服务层与测试共用同一份真值）。
 *
 * 为什么单独放一个文件：`DataService` 已经很大，而这两个数字既要被服务层引用，
 * 也要被 `apps/api/test/**` 的断言引用（`Math.ceil(N / BATCH)`）——
 * 若写成 `data.service.ts` 里的私有常量，测试就必须复制一份数字（魔法数字，
 * 且改了服务层不会红）。放这里两边都 `import` 同一个符号，改动只可能同步。
 */

/**
 * **每个事务最多承载多少条 upsert**（分批写入的批大小）。
 *
 * ### 取值 500 的理由
 *
 * ① **避开 Prisma 的事务超时（缺陷的根源）**。Prisma 事务默认 5 秒超时（错误码
 * `P2028`），而 `POST /api/data/import/weights` 的历史实现把 N 条 upsert
 * **全塞进一条 `$transaction`**：2000 行（= {@link MAX_IMPORT_ROWS} 上限，约 5 年
 * 逐日记录，自用场景完全可能）时，单事务持锁时间轻易超过 5 秒，**整批回滚、
 * 一行都进不去**。切成 500 后，满额 2000 行 = 4 个事务，每个事务只有 500 条
 * 写，实测远低于 1 秒，离 5 秒上限有充分余量。
 *
 * ② **限制 SQLite 写锁的持有时长**。SQLite 是**单写者**：一个写事务会独占写锁，
 * 期间其它写请求只能等（本项目虽是单人自用，但导入时若前端还在轮询/写入就会撞上）。
 * 批越小、锁的单次持有时间越短；批越大、事务开销（BEGIN/COMMIT）摊得越薄。
 * 500 是这两者的折中：单批写锁在百毫秒级，事务固定开销也只付 4 次。
 *
 * ③ **不取更小值（如 100）的原因**：满额导入会变成 20 个事务，BEGIN/COMMIT 与
 * 往返开销线性增加，而单批 100 条相对 500 条并没有实质性地更不容易超时 ——
 * 事务耗时主要由**固定开销**主导，不是由条数线性主导。
 */
export const WEIGHT_IMPORT_BATCH_SIZE = 500;
